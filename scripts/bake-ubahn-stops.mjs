/**
 * Writes the stop lookup the VBB realtime feed needs.
 *
 * That feed identifies stops by DHID (`de:11000:900023302::1`) and carries no
 * names or coordinates. The numeric core of a DHID is the same BVG stop id the
 * U-Bahn geometry is already baked with, so the join needs nothing more than
 * the file `prepare-geo`/`fetch-ubahn` already produce.
 *
 *   node scripts/bake-ubahn-stops.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "public/geo/berlin-ubahn.geojson");
const target = resolve(root, "src/data/ubahnStops.js");

const geo = JSON.parse(await readFile(source, "utf8"));
const stations = geo.features.filter((f) => f.properties?.kind === "station");

const stops = {};
let skipped = 0;
for (const station of stations) {
  const id = String(station.properties.id || "");
  // OSM-only stations have no BVG id, so the feed can never refer to them.
  if (!id || id.startsWith("osm:")) {
    skipped += 1;
    continue;
  }
  const [lng, lat] = station.geometry.coordinates;
  stops[id] = [
    Number(lat.toFixed(5)),
    Number(lng.toFixed(5)),
    station.properties.name,
    station.properties.lines || [],
  ];
}

const body = `// Generated by scripts/bake-ubahn-stops.mjs — do not edit by hand.
// BVG stop id -> [lat, lng, name, lines]. Used to place the VBB realtime feed's
// trips, which identify stops by id only.
export const UBAHN_STOPS = ${JSON.stringify(stops, null, 0)};
`;

await writeFile(target, body, "utf8");
console.log(
  `Wrote ${Object.keys(stops).length} stops to src/data/ubahnStops.js` +
    (skipped ? ` (${skipped} without a BVG id skipped)` : "")
);
